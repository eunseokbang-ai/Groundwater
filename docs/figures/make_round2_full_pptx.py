class Full(UP.Update):
    def divider(self, part):
        num, title, sub, col = part
        s = self.prs.slides.add_slide(self.blank)
        self.rect(s, 0, 0, W_IN, H_IN, DARK)
        self.rect(s, 0, 0, 0.18, H_IN, col)
        self.text(s, 0.9, 2.2, 11.5, 1.0, [(num if num == "부록" else f"PART {num}", 22, True, "9CA3AF")])
        self.text(s, 0.9, 2.9, 11.5, 1.2, [(title, 40, True, "FFFFFF")])
        if sub:
            self.text(s, 0.9, 4.15, 11.5, 1.0, [(sub, 18, False, "D1D5DB")])
        UP.Update._notes(self, s, f"{title}: {sub}")
        self.slides.append(s)
        return s

    def _notes(self, s, notes):
        ns = s.notes_slide
        if ns.notes_text_frame is None:
            import copy

            for el in self._notes_tpl:
                ns.shapes._spTree.append(copy.deepcopy(el))
        ns.notes_text_frame.text = notes

    def card(self, s, x, y, w, h, head, body, col, size=14):
        self.rect(s, x, y, w, h, "FFFFFF", line=LINE, shape=MSO_SHAPE.ROUNDED_RECTANGLE).adjustments[0] = 0.06
        self.rect(s, x, y, w, 0.5, col, shape=MSO_SHAPE.RECTANGLE)
        self.text(s, x + 0.12, y + 0.04, w - 0.24, 0.45, [(head, 15, True, "FFFFFF")], anchor=MSO_ANCHOR.MIDDLE)
        self.bullets(s, x + 0.1, y + 0.6, w - 0.2, h - 0.7, body, size=size, colour=col, gap=4)

    def arrow(self, s, x, y, w, h=0.32, col="9CA3AF"):
        a = s.shapes.add_shape(MSO_SHAPE.RIGHT_ARROW, Inches(x), Inches(y), Inches(w), Inches(h))
        a.fill.solid()
        a.fill.fore_color.rgb = UP.rgb(col)
        a.line.fill.background()


UP.Update._notes = Full._notes


