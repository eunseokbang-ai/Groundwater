def _para(s, old, new):
    """The paragraph whose text is `old` gets `new` (formatting of its first text run; a bullet run "• " is kept)."""
    for sh in s.shapes:
        frames = [sh.text_frame] if sh.has_text_frame else []
        if sh.has_table:
            frames += [c.text_frame for r in sh.table.rows for c in r.cells]
        for tf in frames:
            for p in tf.paragraphs:
                j = "".join(r.text for r in p.runs)
                if j == old or (j.startswith("• ") and j[2:] == old):
                    runs = list(p.runs)
                    k = 1 if len(runs) > 1 and runs[0].text.strip() == "•" else 0
                    runs[k].text = new
                    for r in runs[k + 1:]:
                        r._r.getparent().remove(r._r)
                    return
    raise KeyError(old)


