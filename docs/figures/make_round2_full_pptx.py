def _swap_pic(pic, path):
    """The picture's image replaced by `path`, fitted (aspect kept) and centred in the picture's old box."""
    from PIL import Image

    rid = pic._element.blipFill.blip.rEmbed
    part = pic.part.related_part(rid)
    part._blob = Path(path).read_bytes()
    with Image.open(path) as im:
        iw, ih = im.size
    x, y, w, h = pic.left, pic.top, pic.width, pic.height
    k = min(w / iw, h / ih)
    pic.width, pic.height = int(iw * k), int(ih * k)
    pic.left, pic.top = x + (w - pic.width) // 2, y + (h - pic.height) // 2
    pic.crop_left = pic.crop_right = pic.crop_top = pic.crop_bottom = 0


def _set_table(tbl, rows):
    """Cell texts (str or (text, hex colour)) written into the table's runs; rows added (copies of the last) or
    removed to match."""
    import copy

    from make_round2_pptx import rgb

    tr = tbl._tbl.tr_lst
    while len(tr) < len(rows):
        tbl._tbl.append(copy.deepcopy(tr[-1]))
        tr = tbl._tbl.tr_lst
    while len(tr) > len(rows):
        tbl._tbl.remove(tr[-1])
        tr = tbl._tbl.tr_lst
    for i, row in enumerate(rows):
        for j, v in enumerate(row):
            text, col = (v if isinstance(v, tuple) else (str(v), None))
            p = tbl.cell(i, j).text_frame.paragraphs[0]
            runs = list(p.runs)
            if not runs:
                p.add_run()
                runs = list(p.runs)
            runs[0].text = str(text)
            for r in runs[1:]:
                r._r.getparent().remove(r._r)
            if col:
                runs[0].font.color.rgb = rgb(col)


